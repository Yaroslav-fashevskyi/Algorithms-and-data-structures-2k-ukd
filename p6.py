# Цифри числа зліва направо
# Дано натуральне число N. Виведіть всі його цифри по одній, у звичному порядку, разділюючи їх пробілами або новими рядками.

def print_digits(n):
    if n == 0:
        return

    print_digits(n // 10)
    print(n % 10, end=" ")


n = int(input("Введіьть натуральне число: "))
print_digits(n)