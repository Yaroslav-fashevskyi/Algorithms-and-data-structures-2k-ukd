# Цифри числа справа наліво
# Дано натуральне число N. Виведіть всі його цифри по одній, у зворотному порядку, розділюючи їх пробілами або новим рядком.

def print_reverse(n):
    if n == 0:
        return

    print(n % 10, end=" ")
    print_reverse(n // 10)


n = int(input("Введіть натуральне число n: "))
print_reverse(n)